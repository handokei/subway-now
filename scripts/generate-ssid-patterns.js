#!/usr/bin/env node
/**
 * #1216 (Epic #1204, D-DATA) — 528 역 subway wifi SSID 패턴 자동 확장.
 *
 * 입력: src/data/stations.json (533 entry, 448 unique 한글 역명)
 * 출력: src/data/subwayWifiSsidMap.json
 *
 * 전략:
 * - 기존 수동 등록 entry (19건)는 그대로 보존 — 현장 수집된 실측 패턴 신뢰성 유지.
 * - 미등록 역에 한해 통신사 default 패턴(SKT/KT/LGU+) 3종 + 영문 패턴 1종을 자동 생성.
 * - 통신사 prefix는 CARRIER_PATTERNS 상수에 분리 (글로벌 룰 #3 데이터 주도).
 *
 * 사용법: node scripts/generate-ssid-patterns.js
 * 단위 테스트: scripts/__tests__/generate-ssid-patterns.test.js
 */

'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const STATIONS_JSON = path.join(ROOT, 'src', 'data', 'stations.json');
const SSID_MAP_JSON = path.join(ROOT, 'src', 'data', 'subwayWifiSsidMap.json');

/**
 * 통신사별 SSID prefix 패턴. 값은 정규식의 prefix (앵커 포함).
 * 실제 통신사 운영 명명규칙 기반 (T_subway_*, Olleh_Subway_*, U+Subway_*).
 */
const CARRIER_PATTERNS = Object.freeze([
  { id: 'skt', prefix: '^T_subway_' },
  { id: 'kt', prefix: '^Olleh_Subway_' },
  { id: 'lgu', prefix: 'U\\+Subway_' },
]);

/**
 * 영문 역명을 SSID 매칭용 토큰으로 정규화한다.
 * - 공백/탭 → underscore
 * - 알파벳·숫자·underscore 외 문자 제거
 * - 빈 문자열이면 null
 */
function normalizeEnglishToken(nameEn) {
  if (typeof nameEn !== 'string') return null;
  const trimmed = nameEn.trim();
  if (trimmed.length === 0) return null;
  const compact = trimmed.replace(/\s+/g, '_').replace(/[^A-Za-z0-9_]/g, '');
  return compact.length === 0 ? null : compact;
}

/**
 * 단일 역에 대한 자동 생성 패턴 배열을 만든다.
 * - 통신사 3종 × 한글 역명
 * - 영문 토큰 (있을 경우)
 */
function buildAutoPatterns(stationName, nameEn) {
  const patterns = CARRIER_PATTERNS.map((c) => `${c.prefix}${stationName}`);
  const enToken = normalizeEnglishToken(nameEn);
  if (enToken !== null) patterns.push(enToken);
  return patterns;
}

/**
 * stations.json + 기존 manual entries를 받아 최종 entries 배열을 만든다.
 * - manual entry는 stationName 기준으로 우선 보존.
 * - 미등록 unique 한글명에 한해 auto 생성.
 * 반환: { entries, manualEntriesCount, autoGeneratedCount }
 */
function buildEntries(stations, manualEntries) {
  const manualNames = new Set(manualEntries.map((e) => e.stationName));
  const seenAuto = new Set();
  const autoEntries = [];

  for (const station of stations) {
    const { name, nameEn } = station;
    if (typeof name !== 'string' || name.length === 0) continue;
    if (manualNames.has(name)) continue;
    if (seenAuto.has(name)) continue;
    seenAuto.add(name);
    autoEntries.push({
      stationName: name,
      patterns: buildAutoPatterns(name, nameEn),
    });
  }

  // Sort auto entries by stationName for deterministic JSON diffs.
  autoEntries.sort((a, b) => a.stationName.localeCompare(b.stationName, 'ko'));

  return {
    entries: [...manualEntries, ...autoEntries],
    manualEntriesCount: manualEntries.length,
    autoGeneratedCount: autoEntries.length,
  };
}

/**
 * 최종 JSON 객체를 구성한다. (_meta 갱신 포함)
 */
function buildOutput(stations, existingMap, nowIso) {
  const manualEntries = Array.isArray(existingMap.entries) ? existingMap.entries : [];
  const built = buildEntries(stations, manualEntries);
  const meta = {
    ...(existingMap._meta ?? {}),
    generatedAt: nowIso,
    patternStrategy: 'carrier-default-with-station-name',
    manualEntriesCount: built.manualEntriesCount,
    autoGeneratedCount: built.autoGeneratedCount,
    totalEntries: built.entries.length,
    dataCollection:
      '수동 등록 19건은 현장 수집 패턴(보존). 나머지는 통신사 default + 한/영 역명 조합으로 자동 생성. 추후 현장 수집으로 점진 교체.',
  };
  return {
    $schema: existingMap.$schema ?? './subwayWifiSsidMap.schema',
    _meta: meta,
    entries: built.entries,
  };
}

function readJson(filePath) {
  const raw = fs.readFileSync(filePath, 'utf8');
  return JSON.parse(raw);
}

function writeJson(filePath, data) {
  fs.writeFileSync(filePath, `${JSON.stringify(data, null, 2)}\n`, 'utf8');
}

function main({ logger = console } = {}) {
  const stations = readJson(STATIONS_JSON);
  const existingMap = readJson(SSID_MAP_JSON);
  const output = buildOutput(stations, existingMap, new Date().toISOString());
  writeJson(SSID_MAP_JSON, output);
  logger.log(
    `[generate-ssid-patterns] manual=${output._meta.manualEntriesCount} auto=${output._meta.autoGeneratedCount} total=${output._meta.totalEntries}`,
  );
  return output;
}

/* istanbul ignore next -- CLI entry point */
if (require.main === module) {
  main();
}

module.exports = {
  CARRIER_PATTERNS,
  normalizeEnglishToken,
  buildAutoPatterns,
  buildEntries,
  buildOutput,
  readJson,
  writeJson,
  main,
  STATIONS_JSON,
  SSID_MAP_JSON,
};
